--==============================================================================
-- Patch : NOTIF_INBOX (per-user in-app notifications)
-- Scope : UM schema, idempotent. Safe to re-run.
--
-- One row per (recipient_user, message). The producer fans out by username at
-- publish time so "mark as read" is a single-row update.
--
-- v2 plans (additive; safe later):
--   * ROLE_TYPE NUMBER (broadcast to a role).
--   * NOTIF_INBOX_READ (id, username, read_at) if we ever switch to a single
--     canonical row + per-user read markers.
--==============================================================================

DECLARE
  v_count NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_count
    FROM ALL_TABLES
   WHERE OWNER = 'UM' AND TABLE_NAME = 'NOTIF_INBOX';

  IF v_count = 0 THEN
    EXECUTE IMMEDIATE q'[
      CREATE TABLE UM.NOTIF_INBOX (
        ID            NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
        USERNAME      VARCHAR2(200) NOT NULL,
        CATEGORY      VARCHAR2(40)  NOT NULL,
        SEVERITY      VARCHAR2(16)  NOT NULL,
        TITLE         VARCHAR2(300) NOT NULL,
        BODY          VARCHAR2(2000),
        LINK_ROUTE    VARCHAR2(400),
        RESOURCE_TYPE VARCHAR2(64),
        RESOURCE_ID   VARCHAR2(64),
        READ_AT       TIMESTAMP,
        CREATED_AT    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
        CONSTRAINT CK_NOTIF_INBOX_SEVERITY CHECK (SEVERITY IN ('INFO','SUCCESS','WARN','ERROR'))
      )
    ]';
  END IF;
END;
/

-- Index for the hot read path: latest items for one user, then unread filter.
DECLARE
  v_count NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_count
    FROM ALL_INDEXES
   WHERE OWNER = 'UM' AND INDEX_NAME = 'IDX_NOTIF_INBOX_USER_CREATED';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE q'[
      CREATE INDEX UM.IDX_NOTIF_INBOX_USER_CREATED
        ON UM.NOTIF_INBOX (USERNAME, CREATED_AT DESC)
    ]';
  END IF;
END;
/

-- Index for unread-count lookups (small, partial-style via composite).
DECLARE
  v_count NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_count
    FROM ALL_INDEXES
   WHERE OWNER = 'UM' AND INDEX_NAME = 'IDX_NOTIF_INBOX_USER_UNREAD';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE q'[
      CREATE INDEX UM.IDX_NOTIF_INBOX_USER_UNREAD
        ON UM.NOTIF_INBOX (USERNAME, READ_AT)
    ]';
  END IF;
END;
/

-- Index for resource lookups (de-dup checks: "did we already publish a
-- 60-min reminder for appointment 42?").
DECLARE
  v_count NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_count
    FROM ALL_INDEXES
   WHERE OWNER = 'UM' AND INDEX_NAME = 'IDX_NOTIF_INBOX_RESOURCE';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE q'[
      CREATE INDEX UM.IDX_NOTIF_INBOX_RESOURCE
        ON UM.NOTIF_INBOX (RESOURCE_TYPE, RESOURCE_ID)
    ]';
  END IF;
END;
/

COMMIT;
