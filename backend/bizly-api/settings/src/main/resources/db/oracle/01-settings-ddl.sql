-- Settings service tables (schema UM). Run as UM user.

CREATE TABLE UM.SETTINGS_QUERY_DEF (
  ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  NAME VARCHAR2(200) NOT NULL,
  DESCRIPTION VARCHAR2(500),
  SQL_TEXT CLOB NOT NULL,
  PARAMETERS_JSON CLOB,
  CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
  UPDATED_AT TIMESTAMP WITH TIME ZONE,
  CREATED_BY VARCHAR2(120)
);

CREATE UNIQUE INDEX UX_SETTINGS_QUERY_DEF_NAME ON UM.SETTINGS_QUERY_DEF (UPPER(TRIM(NAME)));

CREATE TABLE UM.SETTINGS_DASHBOARD (
  ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  NAME VARCHAR2(200) NOT NULL,
  SLUG VARCHAR2(120) NOT NULL,
  DESCRIPTION VARCHAR2(500),
  LAYOUT_JSON CLOB,
  IS_BUILTIN NUMBER(1) DEFAULT 0 NOT NULL,
  CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
  UPDATED_AT TIMESTAMP WITH TIME ZONE
);

CREATE UNIQUE INDEX UX_SETTINGS_DASH_SLUG ON UM.SETTINGS_DASHBOARD (LOWER(TRIM(SLUG)));

CREATE TABLE UM.SETTINGS_WIDGET (
  ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  DASHBOARD_ID NUMBER NOT NULL,
  WIDGET_TYPE VARCHAR2(40) NOT NULL,
  TITLE VARCHAR2(300) NOT NULL,
  QUERY_DEF_ID NUMBER,
  CONFIG_JSON CLOB,
  GRID_X NUMBER(10) DEFAULT 0 NOT NULL,
  GRID_Y NUMBER(10) DEFAULT 0 NOT NULL,
  GRID_W NUMBER(10) DEFAULT 4 NOT NULL,
  GRID_H NUMBER(10) DEFAULT 2 NOT NULL,
  REFRESH_SEC NUMBER(10),
  SORT_ORDER NUMBER(10) DEFAULT 0 NOT NULL,
  CONSTRAINT FK_SW_DASH FOREIGN KEY (DASHBOARD_ID) REFERENCES UM.SETTINGS_DASHBOARD(ID) ON DELETE CASCADE,
  CONSTRAINT FK_SW_QUERY FOREIGN KEY (QUERY_DEF_ID) REFERENCES UM.SETTINGS_QUERY_DEF(ID)
);

CREATE INDEX IX_SETTINGS_WIDGET_DASH ON UM.SETTINGS_WIDGET (DASHBOARD_ID);

CREATE TABLE UM.SETTINGS_DASH_ROLE_GRANT (
  DASHBOARD_ID NUMBER NOT NULL,
  ROLE_NAME VARCHAR2(120) NOT NULL,
  CONSTRAINT PK_SD_ROLE PRIMARY KEY (DASHBOARD_ID, ROLE_NAME),
  CONSTRAINT FK_SD_ROLE_D FOREIGN KEY (DASHBOARD_ID) REFERENCES UM.SETTINGS_DASHBOARD(ID) ON DELETE CASCADE
);

CREATE TABLE UM.SETTINGS_DASH_USER_GRANT (
  DASHBOARD_ID NUMBER NOT NULL,
  USERNAME VARCHAR2(120) NOT NULL,
  CONSTRAINT PK_SD_USER PRIMARY KEY (DASHBOARD_ID, USERNAME),
  CONSTRAINT FK_SD_USER_D FOREIGN KEY (DASHBOARD_ID) REFERENCES UM.SETTINGS_DASHBOARD(ID) ON DELETE CASCADE
);

CREATE TABLE UM.SETTINGS_NAV_PREF (
  USERNAME VARCHAR2(120) NOT NULL,
  DASHBOARD_ID NUMBER NOT NULL,
  HIDDEN_NAV NUMBER(1) DEFAULT 1 NOT NULL,
  CONSTRAINT PK_NAV_PREF PRIMARY KEY (USERNAME, DASHBOARD_ID),
  CONSTRAINT FK_NAV_D FOREIGN KEY (DASHBOARD_ID) REFERENCES UM.SETTINGS_DASHBOARD(ID) ON DELETE CASCADE
);
