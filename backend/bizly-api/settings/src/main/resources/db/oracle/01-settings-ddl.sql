-- Settings service tables (schema UM). Run as UM user.

CREATE TABLE UM.SETTINGS_QUERY_DEF (
  ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  NAME VARCHAR2(200) NOT NULL,
  DESCRIPTION VARCHAR2(500),
  SQL_TEXT CLOB NOT NULL,
  PARAMETERS_JSON CLOB,
  CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
  UPDATED_AT TIMESTAMP WITH TIME ZONE,
  CREATED_BY VARCHAR2(120)
);

CREATE UNIQUE INDEX UX_SETTINGS_QUERY_DEF_NAME ON UM.SETTINGS_QUERY_DEF (UPPER(TRIM(NAME)));

CREATE TABLE UM.SETTINGS_DASHBOARD (
  ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  NAME VARCHAR2(200) NOT NULL,
  SLUG VARCHAR2(120) NOT NULL,
  DESCRIPTION VARCHAR2(500),
  LAYOUT_JSON CLOB,
  IS_BUILTIN NUMBER(1) DEFAULT 0 NOT NULL,
  CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
  UPDATED_AT TIMESTAMP WITH TIME ZONE
);

CREATE UNIQUE INDEX UX_SETTINGS_DASH_SLUG ON UM.SETTINGS_DASHBOARD (LOWER(TRIM(SLUG)));

CREATE TABLE UM.SETTINGS_WIDGET (
  ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  DASHBOARD_ID NUMBER NOT NULL,
  WIDGET_TYPE VARCHAR2(40) NOT NULL,
  TITLE VARCHAR2(300) NOT NULL,
  QUERY_DEF_ID NUMBER,
  CONFIG_JSON CLOB,
  GRID_X NUMBER(10) DEFAULT 0 NOT NULL,
  GRID_Y NUMBER(10) DEFAULT 0 NOT NULL,
  GRID_W NUMBER(10) DEFAULT 4 NOT NULL,
  GRID_H NUMBER(10) DEFAULT 2 NOT NULL,
  REFRESH_SEC NUMBER(10),
  SORT_ORDER NUMBER(10) DEFAULT 0 NOT NULL,
  CONSTRAINT FK_SW_DASH FOREIGN KEY (DASHBOARD_ID) REFERENCES UM.SETTINGS_DASHBOARD(ID) ON DELETE CASCADE,
  CONSTRAINT FK_SW_QUERY FOREIGN KEY (QUERY_DEF_ID) REFERENCES UM.SETTINGS_QUERY_DEF(ID)
);

CREATE INDEX IX_SETTINGS_WIDGET_DASH ON UM.SETTINGS_WIDGET (DASHBOARD_ID);

-- Grants are keyed by UM_ROLE.ROLE_TYPE (numeric, stable) so renaming a role
-- in UM_ROLE.NAME never invalidates any dashboard permission.
CREATE TABLE UM.SETTINGS_DASH_ROLE_GRANT (
  DASHBOARD_ID NUMBER NOT NULL,
  ROLE_TYPE NUMBER(10) NOT NULL,
  ROLE_NAME VARCHAR2(200),
  CONSTRAINT PK_SD_ROLE PRIMARY KEY (DASHBOARD_ID, ROLE_TYPE),
  CONSTRAINT FK_SD_ROLE_D FOREIGN KEY (DASHBOARD_ID) REFERENCES UM.SETTINGS_DASHBOARD(ID) ON DELETE CASCADE
);

CREATE TABLE UM.SETTINGS_DASH_USER_GRANT (
  DASHBOARD_ID NUMBER NOT NULL,
  USERNAME VARCHAR2(120) NOT NULL,
  CONSTRAINT PK_SD_USER PRIMARY KEY (DASHBOARD_ID, USERNAME),
  CONSTRAINT FK_SD_USER_D FOREIGN KEY (DASHBOARD_ID) REFERENCES UM.SETTINGS_DASHBOARD(ID) ON DELETE CASCADE
);

CREATE TABLE UM.SETTINGS_NAV_PREF (
  USERNAME VARCHAR2(120) NOT NULL,
  DASHBOARD_ID NUMBER NOT NULL,
  HIDDEN_NAV NUMBER(1) DEFAULT 1 NOT NULL,
  CONSTRAINT PK_NAV_PREF PRIMARY KEY (USERNAME, DASHBOARD_ID),
  CONSTRAINT FK_NAV_D FOREIGN KEY (DASHBOARD_ID) REFERENCES UM.SETTINGS_DASHBOARD(ID) ON DELETE CASCADE
);

-- Per-user scalar preferences (e.g. last opened dashboard) so the UI can land
-- the user on their previous selection after login instead of an arbitrary default.
CREATE TABLE UM.SETTINGS_USER_PREF (
  USERNAME           VARCHAR2(120) NOT NULL,
  LAST_DASHBOARD_ID  NUMBER,
  UPDATED_AT         TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT PK_SETTINGS_USER_PREF PRIMARY KEY (USERNAME),
  CONSTRAINT FK_SUP_LAST_DASH FOREIGN KEY (LAST_DASHBOARD_ID)
    REFERENCES UM.SETTINGS_DASHBOARD(ID) ON DELETE SET NULL
);

-- Starred menus per user, plus the single one (max 1) flagged as default
-- landing screen for the login flow. We don't FK menu_route -> UM_MENU so a
-- temporarily disabled menu doesn't blow away the user's preference; the UI
-- filters favorites against the live accessible menu list at render time.
CREATE TABLE UM.SETTINGS_USER_FAVORITE (
  USERNAME    VARCHAR2(120) NOT NULL,
  MENU_ROUTE  VARCHAR2(400) NOT NULL,
  PIN_ORDER   NUMBER(10) DEFAULT 0 NOT NULL,
  IS_DEFAULT  NUMBER(1)  DEFAULT 0 NOT NULL,
  CREATED_AT  TIMESTAMP  DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_SETTINGS_USER_FAV PRIMARY KEY (USERNAME, MENU_ROUTE),
  CONSTRAINT CK_SUF_DEFAULT CHECK (IS_DEFAULT IN (0,1))
);

CREATE INDEX UM.IDX_USER_FAV_USER_ORDER
  ON UM.SETTINGS_USER_FAVORITE (USERNAME, PIN_ORDER);

-- Non-unique index for "find this user's default favorite" lookups.
-- Uniqueness of IS_DEFAULT=1 per user is enforced in SettingsUserFavoritesService
-- (dedupe -> clear -> set, plus self-heal on every list()).
CREATE INDEX UM.IDX_USER_FAV_DEFAULT
  ON UM.SETTINGS_USER_FAVORITE (USERNAME, IS_DEFAULT);

-- Report Builder: user-defined reports backed by SETTINGS_QUERY_DEF.
-- The Reporting screen (and the sidebar Reports section) reads from here;
-- the legacy hardcoded providers have been retired.
CREATE TABLE UM.SETTINGS_REPORT (
  ID                NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  CODE              VARCHAR2(120) NOT NULL,
  NAME              VARCHAR2(200) NOT NULL,
  DESCRIPTION       VARCHAR2(500),
  ICON              VARCHAR2(80),
  STATUS            VARCHAR2(20)  DEFAULT 'ACTIVE' NOT NULL,
  QUERY_DEF_ID      NUMBER        NOT NULL,
  FILTERS_JSON      CLOB,
  COLUMNS_JSON      CLOB,
  DEFAULT_SORT_KEY  VARCHAR2(200),
  DEFAULT_SORT_DIR  VARCHAR2(8),
  SORT_ORDER        NUMBER(10)    DEFAULT 0 NOT NULL,
  CREATED_AT        TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,
  UPDATED_AT        TIMESTAMP,
  CREATED_BY        VARCHAR2(120),
  UPDATED_BY        VARCHAR2(120),
  CONSTRAINT UX_SETTINGS_REPORT_CODE UNIQUE (CODE),
  CONSTRAINT UX_SETTINGS_REPORT_NAME UNIQUE (NAME),
  CONSTRAINT FK_SETTINGS_REPORT_QDEF FOREIGN KEY (QUERY_DEF_ID)
    REFERENCES UM.SETTINGS_QUERY_DEF (ID)
);

CREATE INDEX UM.IDX_SETTINGS_REPORT_STATUS
  ON UM.SETTINGS_REPORT (STATUS, SORT_ORDER, NAME);

CREATE INDEX UM.IDX_SETTINGS_REPORT_QDEF
  ON UM.SETTINGS_REPORT (QUERY_DEF_ID);
