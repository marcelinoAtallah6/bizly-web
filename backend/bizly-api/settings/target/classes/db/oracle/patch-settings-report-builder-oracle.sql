-- =============================================================================
-- Report Builder — SETTINGS_REPORT
-- Schema: UM. Idempotent: safe to re-run.
--
-- One row = one user-defined report built on top of a SETTINGS_QUERY_DEF.
-- The Reporting screen reads from this table (no hardcoded providers) and the
-- sidebar renders one entry per ACTIVE report.
-- =============================================================================

DECLARE
  v_exists NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_exists FROM ALL_TABLES
   WHERE OWNER = 'UM' AND TABLE_NAME = 'SETTINGS_REPORT';
  IF v_exists = 0 THEN
    EXECUTE IMMEDIATE '
      CREATE TABLE UM.SETTINGS_REPORT (
        ID                NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
        CODE              VARCHAR2(120) NOT NULL,
        NAME              VARCHAR2(200) NOT NULL,
        DESCRIPTION       VARCHAR2(500),
        ICON              VARCHAR2(80),
        STATUS            VARCHAR2(20)  DEFAULT ''ACTIVE'' NOT NULL,
        QUERY_DEF_ID      NUMBER        NOT NULL,
        FILTERS_JSON      CLOB,
        COLUMNS_JSON      CLOB,
        DEFAULT_SORT_KEY  VARCHAR2(200),
        DEFAULT_SORT_DIR  VARCHAR2(8),
        SORT_ORDER        NUMBER(10)    DEFAULT 0 NOT NULL,
        CREATED_AT        TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,
        UPDATED_AT        TIMESTAMP,
        CREATED_BY        VARCHAR2(120),
        UPDATED_BY        VARCHAR2(120),
        CONSTRAINT UX_SETTINGS_REPORT_CODE UNIQUE (CODE),
        CONSTRAINT UX_SETTINGS_REPORT_NAME UNIQUE (NAME),
        CONSTRAINT FK_SETTINGS_REPORT_QDEF FOREIGN KEY (QUERY_DEF_ID)
          REFERENCES UM.SETTINGS_QUERY_DEF (ID)
      )';
  END IF;
END;
/

-- Idempotent supporting indexes for the common lookup paths.
DECLARE
  v_exists NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_exists FROM ALL_INDEXES
   WHERE OWNER = 'UM' AND INDEX_NAME = 'IDX_SETTINGS_REPORT_STATUS';
  IF v_exists = 0 THEN
    EXECUTE IMMEDIATE '
      CREATE INDEX UM.IDX_SETTINGS_REPORT_STATUS
        ON UM.SETTINGS_REPORT (STATUS, SORT_ORDER, NAME)';
  END IF;
END;
/

DECLARE
  v_exists NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_exists FROM ALL_INDEXES
   WHERE OWNER = 'UM' AND INDEX_NAME = 'IDX_SETTINGS_REPORT_QDEF';
  IF v_exists = 0 THEN
    EXECUTE IMMEDIATE '
      CREATE INDEX UM.IDX_SETTINGS_REPORT_QDEF
        ON UM.SETTINGS_REPORT (QUERY_DEF_ID)';
  END IF;
END;
/

COMMIT;

