-- Global country reference (shared lookups for travel and other modules)

CREATE TABLE um.ref_country (
  id NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  iso2 CHAR(2) NOT NULL,
  iso3 CHAR(3),
  name VARCHAR2(200) NOT NULL,
  dial_code VARCHAR2(16),
  active NUMBER(1) DEFAULT 1 NOT NULL,
  CONSTRAINT uk_ref_country_iso2 UNIQUE (iso2)
);

CREATE INDEX idx_ref_country_name ON um.ref_country (UPPER(name));

