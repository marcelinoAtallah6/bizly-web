-- =============================================================================
-- Business Registration patch — UM schema
--
-- Adds the data model required by the secure business-registration flow:
--   1. UM_ROLE_LEVEL          — classifies roles (ADMIN vs BUSINESS) so the
--                               registration UI/back-end always knows which
--                               roles are assignable. Adding a new role to a
--                               level is enough to make it appear (or not) in
--                               the registration screen — no code change.
--   2. UM_ROLE                — new columns: ROLE_LEVEL_ID,
--                               IS_DEFAULT_FOR_REGISTRATION,
--                               IS_SYSTEM_RESTRICTED (server-side blocklist).
--   3. UM_BUSINESS            — one row per tenant. Owns its created_by user.
--   4. UM_USER                — new columns:
--                                 BUSINESS_ID    — tenant of the user (NULL
--                                                 for system admins who span
--                                                 every business)
--                                 FIRST_LOGIN    — 1 until the user finishes
--                                                 the welcome wizard
--                                 WELCOME_COMPLETED_AT
--                                 AUTH_PROVIDER  — LOCAL / GOOGLE / FACEBOOK
--                                                 / APPLE
--                                 PROVIDER_USER_ID
--
-- Idempotent.
-- =============================================================================

-- 1) UM_ROLE_LEVEL
DECLARE
  v_exists NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_exists FROM ALL_TABLES
   WHERE OWNER = 'UM' AND TABLE_NAME = 'UM_ROLE_LEVEL';
  IF v_exists = 0 THEN
    EXECUTE IMMEDIATE '
      CREATE TABLE UM.UM_ROLE_LEVEL (
        ID            NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
        CODE          VARCHAR2(40)  NOT NULL,
        NAME          VARCHAR2(120) NOT NULL,
        DESCRIPTION   VARCHAR2(500),
        IS_ASSIGNABLE_ON_REGISTRATION NUMBER(1) DEFAULT 0 NOT NULL,
        SORT_ORDER    NUMBER(10) DEFAULT 0 NOT NULL,
        CREATED_AT    TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
        CONSTRAINT UX_UM_ROLE_LEVEL_CODE UNIQUE (CODE)
      )';
  END IF;
END;
/

-- Seed the two canonical levels (idempotent).
MERGE INTO UM.UM_ROLE_LEVEL t
USING (SELECT 'ADMIN' AS CODE FROM dual) s ON (t.CODE = s.CODE)
WHEN NOT MATCHED THEN INSERT (CODE, NAME, DESCRIPTION, IS_ASSIGNABLE_ON_REGISTRATION, SORT_ORDER)
VALUES ('ADMIN', 'System / Admin', 'Roles that operate across all businesses. Never assignable on self-registration.', 0, 10);

MERGE INTO UM.UM_ROLE_LEVEL t
USING (SELECT 'BUSINESS' AS CODE FROM dual) s ON (t.CODE = s.CODE)
WHEN NOT MATCHED THEN INSERT (CODE, NAME, DESCRIPTION, IS_ASSIGNABLE_ON_REGISTRATION, SORT_ORDER)
VALUES ('BUSINESS', 'Business', 'Roles scoped to a single business. The registration screen only offers roles in this level.', 1, 20);

-- 2) UM_ROLE — new columns
DECLARE
  v_count NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_count FROM ALL_TAB_COLUMNS
   WHERE OWNER = 'UM' AND TABLE_NAME = 'UM_ROLE' AND COLUMN_NAME = 'ROLE_LEVEL_ID';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE UM.UM_ROLE ADD (ROLE_LEVEL_ID NUMBER)';
  END IF;

  SELECT COUNT(*) INTO v_count FROM ALL_TAB_COLUMNS
   WHERE OWNER = 'UM' AND TABLE_NAME = 'UM_ROLE' AND COLUMN_NAME = 'IS_DEFAULT_FOR_REGISTRATION';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE UM.UM_ROLE ADD (IS_DEFAULT_FOR_REGISTRATION NUMBER(1) DEFAULT 0 NOT NULL)';
  END IF;

  SELECT COUNT(*) INTO v_count FROM ALL_TAB_COLUMNS
   WHERE OWNER = 'UM' AND TABLE_NAME = 'UM_ROLE' AND COLUMN_NAME = 'IS_SYSTEM_RESTRICTED';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE UM.UM_ROLE ADD (IS_SYSTEM_RESTRICTED NUMBER(1) DEFAULT 0 NOT NULL)';
  END IF;
END;
/

-- Backfill: classify existing roles by name. Anything starting with SUPER /
-- SYSTEM / ADMIN goes into the ADMIN level; everything else into BUSINESS.
DECLARE
  v_admin_id    NUMBER;
  v_business_id NUMBER;
BEGIN
  SELECT ID INTO v_admin_id    FROM UM.UM_ROLE_LEVEL WHERE CODE = 'ADMIN';
  SELECT ID INTO v_business_id FROM UM.UM_ROLE_LEVEL WHERE CODE = 'BUSINESS';

  UPDATE UM.UM_ROLE
     SET ROLE_LEVEL_ID = v_admin_id,
         IS_SYSTEM_RESTRICTED = 1
   WHERE ROLE_LEVEL_ID IS NULL
     AND (UPPER(NAME) IN ('SUPER_ADMIN', 'SYSTEM_ADMIN', 'ADMIN')
          OR UPPER(NAME) LIKE 'SUPER%' OR UPPER(NAME) LIKE 'SYSTEM%');

  UPDATE UM.UM_ROLE
     SET ROLE_LEVEL_ID = v_business_id,
         IS_SYSTEM_RESTRICTED = 0
   WHERE ROLE_LEVEL_ID IS NULL;
END;
/

-- Ensure a default BUSINESS_ADMIN role exists and is the default registration role.
DECLARE
  v_business_lvl NUMBER;
  v_existing     NUMBER;
BEGIN
  SELECT ID INTO v_business_lvl FROM UM.UM_ROLE_LEVEL WHERE CODE = 'BUSINESS';

  SELECT COUNT(*) INTO v_existing FROM UM.UM_ROLE WHERE UPPER(NAME) = 'BUSINESS_ADMIN';
  IF v_existing = 0 THEN
    INSERT INTO UM.UM_ROLE (NAME, ROLE_TYPE, ROLE_LEVEL_ID, IS_DEFAULT_FOR_REGISTRATION,
                            IS_SYSTEM_RESTRICTED, CREATED_AT)
    VALUES ('BUSINESS_ADMIN', 3, v_business_lvl, 1, 0, SYSTIMESTAMP);
  ELSE
    UPDATE UM.UM_ROLE
       SET ROLE_LEVEL_ID = v_business_lvl,
           IS_DEFAULT_FOR_REGISTRATION = 1,
           IS_SYSTEM_RESTRICTED = 0
     WHERE UPPER(NAME) = 'BUSINESS_ADMIN';
  END IF;

  -- Only one row may carry the default flag — clear any duplicates.
  UPDATE UM.UM_ROLE
     SET IS_DEFAULT_FOR_REGISTRATION = 0
   WHERE IS_DEFAULT_FOR_REGISTRATION = 1
     AND UPPER(NAME) <> 'BUSINESS_ADMIN';
END;
/

ALTER TABLE UM.UM_ROLE
  ADD CONSTRAINT FK_UM_ROLE_LEVEL FOREIGN KEY (ROLE_LEVEL_ID)
  REFERENCES UM.UM_ROLE_LEVEL (ID);

-- 3) UM_BUSINESS — tenant table
DECLARE
  v_exists NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_exists FROM ALL_TABLES
   WHERE OWNER = 'UM' AND TABLE_NAME = 'UM_BUSINESS';
  IF v_exists = 0 THEN
    EXECUTE IMMEDIATE '
      CREATE TABLE UM.UM_BUSINESS (
        ID            NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
        BUSINESS_NAME VARCHAR2(200) NOT NULL,
        BUSINESS_TYPE VARCHAR2(80),
        STATUS        VARCHAR2(20)  DEFAULT ''ACTIVE'' NOT NULL,
        CREATED_BY    NUMBER        NOT NULL,
        CREATED_AT    TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,
        UPDATED_AT    TIMESTAMP,
        CONSTRAINT UX_UM_BUSINESS_NAME UNIQUE (BUSINESS_NAME),
        CONSTRAINT FK_UM_BUSINESS_USER FOREIGN KEY (CREATED_BY) REFERENCES UM.UM_USER (ID)
      )';
  END IF;
END;
/

DECLARE
  v_exists NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_exists FROM ALL_INDEXES
   WHERE OWNER = 'UM' AND INDEX_NAME = 'IDX_UM_BUSINESS_STATUS';
  IF v_exists = 0 THEN
    EXECUTE IMMEDIATE '
      CREATE INDEX UM.IDX_UM_BUSINESS_STATUS ON UM.UM_BUSINESS (STATUS, BUSINESS_NAME)';
  END IF;
END;
/

-- 4) UM_USER — new columns
DECLARE
  v_count NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_count FROM ALL_TAB_COLUMNS
   WHERE OWNER = 'UM' AND TABLE_NAME = 'UM_USER' AND COLUMN_NAME = 'BUSINESS_ID';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE UM.UM_USER ADD (BUSINESS_ID NUMBER)';
    EXECUTE IMMEDIATE 'ALTER TABLE UM.UM_USER ADD CONSTRAINT FK_UM_USER_BUSINESS '
                    || 'FOREIGN KEY (BUSINESS_ID) REFERENCES UM.UM_BUSINESS (ID)';
    EXECUTE IMMEDIATE 'CREATE INDEX UM.IDX_UM_USER_BUSINESS ON UM.UM_USER (BUSINESS_ID)';
  END IF;

  SELECT COUNT(*) INTO v_count FROM ALL_TAB_COLUMNS
   WHERE OWNER = 'UM' AND TABLE_NAME = 'UM_USER' AND COLUMN_NAME = 'FIRST_LOGIN';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE UM.UM_USER ADD (FIRST_LOGIN NUMBER(1) DEFAULT 1 NOT NULL)';
  END IF;

  SELECT COUNT(*) INTO v_count FROM ALL_TAB_COLUMNS
   WHERE OWNER = 'UM' AND TABLE_NAME = 'UM_USER' AND COLUMN_NAME = 'WELCOME_COMPLETED_AT';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE UM.UM_USER ADD (WELCOME_COMPLETED_AT TIMESTAMP)';
  END IF;

  SELECT COUNT(*) INTO v_count FROM ALL_TAB_COLUMNS
   WHERE OWNER = 'UM' AND TABLE_NAME = 'UM_USER' AND COLUMN_NAME = 'AUTH_PROVIDER';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE UM.UM_USER ADD (AUTH_PROVIDER VARCHAR2(20) DEFAULT ''LOCAL'' NOT NULL)';
  END IF;

  SELECT COUNT(*) INTO v_count FROM ALL_TAB_COLUMNS
   WHERE OWNER = 'UM' AND TABLE_NAME = 'UM_USER' AND COLUMN_NAME = 'PROVIDER_USER_ID';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE UM.UM_USER ADD (PROVIDER_USER_ID VARCHAR2(200))';
  END IF;
END;
/

-- Treat existing users as already-onboarded so the wizard only triggers for
-- new sign-ups going forward. New rows default to FIRST_LOGIN = 1.
UPDATE UM.UM_USER SET FIRST_LOGIN = 0 WHERE FIRST_LOGIN IS NULL OR FIRST_LOGIN = 1;
UPDATE UM.UM_USER SET AUTH_PROVIDER = 'LOCAL' WHERE AUTH_PROVIDER IS NULL;

COMMIT;

