-- 7) Backfill role_kind
UPDATE UM.UM_ROLE r
   SET ROLE_KIND = 'ADMIN_INTERNAL'
 WHERE ROLE_KIND IS NULL OR ROLE_KIND = 'BUSINESS_TEAM'
   AND ROLE_LEVEL_ID IN (SELECT ID FROM UM.UM_ROLE_LEVEL WHERE CODE = 'ADMIN');

UPDATE UM.UM_ROLE r
   SET ROLE_KIND = 'BUSINESS_TYPE_TEMPLATE',
       IS_BUSINESS_TYPE = 1
 WHERE (ROLE_KIND IS NULL OR ROLE_KIND = 'BUSINESS_TEAM')
   AND NVL(IS_BUSINESS_TYPE, 0) = 1
   AND BUSINESS_ID IS NULL;

UPDATE UM.UM_ROLE r
   SET ROLE_KIND = 'BUSINESS_TYPE_TEMPLATE'
 WHERE ROLE_KIND IS NULL
   AND ROLE_LEVEL_ID IN (SELECT ID FROM UM.UM_ROLE_LEVEL WHERE CODE = 'BUSINESS')
   AND BUSINESS_ID IS NULL
   AND NVL(IS_BUSINESS_TYPE, 0) = 0
   AND UPPER(NAME) IN ('RESTAURANT','CLINIC','BEAUTY_CENTER','SALON','GYM','TAXI_COMPANY','RETAIL','SERVICES','OTHER');

UPDATE UM.UM_ROLE
   SET ROLE_KIND = 'BUSINESS_TEAM'
 WHERE ROLE_KIND IS NULL;

-- 8) Backfill users
UPDATE UM.UM_USER
   SET USER_TYPE = 'PORTAL_ADMIN',
       IS_BUSINESS_OWNER = 0
 WHERE BUSINESS_ID IS NULL
   AND (USER_TYPE IS NULL OR USER_TYPE = 'BUSINESS_OWNER');

UPDATE UM.UM_USER
   SET USER_TYPE = 'BUSINESS_OWNER',
       IS_BUSINESS_OWNER = 1
 WHERE BUSINESS_ID IS NOT NULL
   AND IS_BUSINESS_OWNER = 0
   AND USER_TYPE IS NULL;

