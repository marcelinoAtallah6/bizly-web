-- ---------------------------------------------------------------------------
-- Versioned pipeline (one published row per action + scope)
-- ---------------------------------------------------------------------------
BEGIN
  EXECUTE IMMEDIATE q'[
    CREATE TABLE UM.UM_WORKFLOW_DEFINITION (
      ID NUMBER(19) NOT NULL,
      ACTION_CODE VARCHAR2(80) NOT NULL,
      VERSION_NO NUMBER(10) NOT NULL,
      STATUS VARCHAR2(20) NOT NULL,
      BUSINESS_ID NUMBER(19),
      DISPLAY_NAME VARCHAR2(200),
      NOTES VARCHAR2(1000),
      PUBLISHED_AT TIMESTAMP,
      PUBLISHED_BY VARCHAR2(120),
      CREATED_BY VARCHAR2(120),
      CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP,
      UPDATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP,
      CONSTRAINT PK_UM_WORKFLOW_DEFINITION PRIMARY KEY (ID),
      CONSTRAINT UK_UM_WF_DEF_SCOPE UNIQUE (ACTION_CODE, VERSION_NO, BUSINESS_ID),
      CONSTRAINT CK_UM_WF_DEF_STATUS CHECK (STATUS IN ('DRAFT', 'PUBLISHED', 'DISABLED'))
    )
  ]';
EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF; END;
/

-- ---------------------------------------------------------------------------
-- Ordered steps (modular types: APPROVAL, NOTIFICATION, extensible later)
-- ---------------------------------------------------------------------------
BEGIN
  EXECUTE IMMEDIATE q'[
    CREATE TABLE UM.UM_WORKFLOW_STEP (
      ID NUMBER(19) NOT NULL,
      DEFINITION_ID NUMBER(19) NOT NULL,
      STEP_ORDER NUMBER(10) NOT NULL,
      STEP_TYPE VARCHAR2(30) NOT NULL,
      IS_ACTIVE NUMBER(1) DEFAULT 1 NOT NULL,
      CONFIG_JSON CLOB NOT NULL,
      WORKFLOW_CONFIG_ID NUMBER(19),
      CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP,
      CONSTRAINT PK_UM_WORKFLOW_STEP PRIMARY KEY (ID),
      CONSTRAINT FK_UM_WF_STEP_DEF FOREIGN KEY (DEFINITION_ID)
        REFERENCES UM.UM_WORKFLOW_DEFINITION (ID),
      CONSTRAINT FK_UM_WF_STEP_CFG FOREIGN KEY (WORKFLOW_CONFIG_ID)
        REFERENCES UM.UM_WORKFLOW_CONFIG (ID),
      CONSTRAINT CK_UM_WF_STEP_TYPE CHECK (STEP_TYPE IN (
        'APPROVAL', 'NOTIFICATION'
      ))
    )
  ]';
EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF; END;
/

BEGIN
  EXECUTE IMMEDIATE 'CREATE INDEX IX_UM_WF_STEP_DEF_ORDER ON UM.UM_WORKFLOW_STEP (DEFINITION_ID, STEP_ORDER)';
EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF; END;
/

-- ---------------------------------------------------------------------------
-- Generic notification outbox (replaces welcome-flag polling over time)
-- ---------------------------------------------------------------------------
BEGIN
  EXECUTE IMMEDIATE q'[
    CREATE TABLE UM.UM_NOTIF_OUTBOX (
      ID NUMBER(19) NOT NULL,
      ACTION_CODE VARCHAR2(80) NOT NULL,
      BUSINESS_ID NUMBER(19),
      CHANNEL VARCHAR2(20) NOT NULL,
      TEMPLATE_KEY VARCHAR2(64),
      RECIPIENT_TYPE VARCHAR2(20) NOT NULL,
      RECIPIENT_ID NUMBER(19),
      RECIPIENT_USERNAME VARCHAR2(120),
      RECIPIENT_EMAIL VARCHAR2(320),
      CONTEXT_JSON CLOB,
      STATUS VARCHAR2(20) NOT NULL,
      IDEMPOTENCY_KEY VARCHAR2(200),
      ATTEMPTS NUMBER(10) DEFAULT 0 NOT NULL,
      LAST_ERROR VARCHAR2(4000),
      SCHEDULED_AT TIMESTAMP,
      PROCESSED_AT TIMESTAMP,
      CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP,
      CONSTRAINT PK_UM_NOTIF_OUTBOX PRIMARY KEY (ID),
      CONSTRAINT CK_UM_NOTIF_OUTBOX_CH CHECK (CHANNEL IN ('EMAIL', 'INBOX', 'BOTH')),
      CONSTRAINT CK_UM_NOTIF_OUTBOX_ST CHECK (STATUS IN (
        'PENDING', 'PROCESSING', 'SENT', 'FAILED', 'CANCELLED'
      )),
      CONSTRAINT CK_UM_NOTIF_OUTBOX_RCPT CHECK (RECIPIENT_TYPE IN (
        'USER', 'CUSTOMER', 'USERNAME', 'EMAIL'
      ))
    )
  ]';
EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF; END;
/

BEGIN
  EXECUTE IMMEDIATE 'CREATE UNIQUE INDEX UK_UM_NOTIF_OUTBOX_IDEM ON UM.UM_NOTIF_OUTBOX (IDEMPOTENCY_KEY)';
