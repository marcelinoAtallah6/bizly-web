-- =============================================================================
-- UM approval workflow: tables, sequences, built-in business registration config,
-- and sidebar menu routes (Oracle).
-- Run once per environment. PL/SQL blocks tolerate "already exists".
-- =============================================================================

BEGIN
  EXECUTE IMMEDIATE 'CREATE SEQUENCE UM.S_UM_WORKFLOW_CONFIG START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE';
EXCEPTION
  WHEN OTHERS THEN
    IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

BEGIN
  EXECUTE IMMEDIATE 'CREATE SEQUENCE UM.S_UM_WORKFLOW_INSTANCE START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE';
EXCEPTION
  WHEN OTHERS THEN
    IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

BEGIN
  EXECUTE IMMEDIATE q'[
    CREATE TABLE UM.UM_WORKFLOW_CONFIG (
      ID NUMBER(19) NOT NULL,
      SCREEN_NAME VARCHAR2(200) NOT NULL,
      ACTION_NAME VARCHAR2(200) NOT NULL,
      HAS_WORKFLOW NUMBER(1) NOT NULL,
      LEVEL_COUNT NUMBER(10) NOT NULL,
      MAKER_ROLES_JSON CLOB,
      CHECKER_ROLES_JSON CLOB,
      MAKER_USERS_JSON CLOB,
      CHECKER_USERS_JSON CLOB,
      BUILT_IN_KEY VARCHAR2(80),
      BUSINESS_ID NUMBER(19),
      CREATED_BY VARCHAR2(120),
      CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP,
      CONSTRAINT PK_UM_WORKFLOW_CONFIG PRIMARY KEY (ID)
    )
  ]';
EXCEPTION
  WHEN OTHERS THEN
    IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

BEGIN
  EXECUTE IMMEDIATE q'[
    CREATE TABLE UM.UM_WORKFLOW_INSTANCE (
      ID NUMBER(19) NOT NULL,
      WORKFLOW_CONFIG_ID NUMBER(19) NOT NULL,
      BUSINESS_ID NUMBER(19) NOT NULL,
      TRIGGERED_BY_USER_ID NUMBER(19),
      TRIGGERED_BY_USERNAME VARCHAR2(120),
      CURRENT_LEVEL NUMBER(10) NOT NULL,
      STATUS VARCHAR2(20) NOT NULL,
      PAYLOAD_JSON CLOB,
      SCREEN_NAME VARCHAR2(200),
      ACTION_NAME VARCHAR2(200),
      CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP,
      UPDATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP,
      CONSTRAINT PK_UM_WORKFLOW_INSTANCE PRIMARY KEY (ID),
      CONSTRAINT FK_WFI_CFG FOREIGN KEY (WORKFLOW_CONFIG_ID) REFERENCES UM.UM_WORKFLOW_CONFIG (ID)
    )
  ]';
EXCEPTION
  WHEN OTHERS THEN
    IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

INSERT INTO UM.UM_WORKFLOW_CONFIG (
  ID, SCREEN_NAME, ACTION_NAME, HAS_WORKFLOW, LEVEL_COUNT,
  MAKER_ROLES_JSON, CHECKER_ROLES_JSON, MAKER_USERS_JSON, CHECKER_USERS_JSON,
  BUILT_IN_KEY, BUSINESS_ID, CREATED_BY, CREATED_AT
)
SELECT
  UM.S_UM_WORKFLOW_CONFIG.NEXTVAL,
  'Onboarding',
  'Business registration',
  1,
  1,
  NULL,
  '["SUPER_ADMIN","ADMIN"]',
  NULL,
  NULL,
  'BUSINESS_REGISTRATION',
  NULL,
  'SYSTEM',
  SYSTIMESTAMP
FROM DUAL
WHERE NOT EXISTS (
  SELECT 1 FROM UM.UM_WORKFLOW_CONFIG c WHERE c.BUILT_IN_KEY = 'BUSINESS_REGISTRATION' AND c.BUSINESS_ID IS NULL
);

INSERT INTO UM.UM_MENUS (ID, APPLICATION_ID, PARENT_ID, NAME, ROUTE, ICON, IS_ACTIVE, ALLOWED_ROLES)
SELECT UM.S_UM_MENUS.NEXTVAL, a.ID, NULL, 'Approval queue', '/um/workflow-queue', NULL, 1, NULL
FROM UM.UM_APPLICATIONS a
WHERE (UPPER(a.NAME) LIKE '%UM%' OR UPPER(a.NAME) LIKE '%USER MANAGEMENT%' OR UPPER(a.NAME) = 'UM')
  AND a.IS_ACTIVE = 1
  AND ROWNUM = 1
  AND NOT EXISTS (SELECT 1 FROM UM.UM_MENUS m WHERE m.ROUTE = '/um/workflow-queue');

INSERT INTO UM.UM_MENUS (ID, APPLICATION_ID, PARENT_ID, NAME, ROUTE, ICON, IS_ACTIVE, ALLOWED_ROLES)
SELECT UM.S_UM_MENUS.NEXTVAL, a.ID, NULL, 'Workflow configuration', '/um/workflow-config', NULL, 1, NULL
FROM UM.UM_APPLICATIONS a
WHERE (UPPER(a.NAME) LIKE '%UM%' OR UPPER(a.NAME) LIKE '%USER MANAGEMENT%' OR UPPER(a.NAME) = 'UM')
  AND a.IS_ACTIVE = 1
  AND ROWNUM = 1
  AND NOT EXISTS (SELECT 1 FROM UM.UM_MENUS m WHERE m.ROUTE = '/um/workflow-config');

