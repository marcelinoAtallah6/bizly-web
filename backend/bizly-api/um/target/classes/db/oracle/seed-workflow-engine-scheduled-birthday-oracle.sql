-- Published pipelines (global). Column names match patch-um-workflow-engine-oracle.sql + v2 patch.
DECLARE
  v_user_ep NUMBER;
  v_cust_ep NUMBER;
  v_def_id NUMBER;
  v_has_v2 NUMBER := 0;
BEGIN
  SELECT COUNT(*) INTO v_has_v2
  FROM ALL_TAB_COLUMNS
  WHERE OWNER = 'UM' AND TABLE_NAME = 'UM_WORKFLOW_DEFINITION' AND COLUMN_NAME = 'WORKFLOW_TYPE';

  SELECT ID INTO v_user_ep FROM UM.UM_WORKFLOW_API_ENDPOINT WHERE ENGINE_ACTION_CODE = 'BIRTHDAY_USER_SUCCESS' AND ROWNUM = 1;
  SELECT ID INTO v_cust_ep FROM UM.UM_WORKFLOW_API_ENDPOINT WHERE ENGINE_ACTION_CODE = 'BIRTHDAY_CUSTOMER_SUCCESS' AND ROWNUM = 1;

  -- User birthday pipeline
  BEGIN
    SELECT ID INTO v_def_id
    FROM UM.UM_WORKFLOW_DEFINITION
    WHERE ACTION_CODE = 'EP:' || v_user_ep AND BUSINESS_ID IS NULL AND STATUS = 'PUBLISHED' AND ROWNUM = 1;
  EXCEPTION
    WHEN NO_DATA_FOUND THEN
      INSERT INTO UM.UM_WORKFLOW_DEFINITION (
        ID, ACTION_CODE, VERSION_NO, STATUS, BUSINESS_ID, DISPLAY_NAME, NOTES,
        PUBLISHED_AT, PUBLISHED_BY, CREATED_BY, CREATED_AT, UPDATED_AT
      ) VALUES (
        UM.S_UM_WORKFLOW_DEFINITION.NEXTVAL, 'EP:' || v_user_ep, 1, 'PUBLISHED', NULL,
        'User birthday email', 'Scheduled daily — WorkflowEngineScheduledTriggerService',
        SYSTIMESTAMP, 'seed', 'seed', SYSTIMESTAMP, SYSTIMESTAMP
      )
      RETURNING ID INTO v_def_id;
  END;

  IF v_has_v2 > 0 THEN
    UPDATE UM.UM_WORKFLOW_DEFINITION
    SET WORKFLOW_TYPE = 'NOTIFICATION_ONLY',
        ROLE_RESTRICTED = 0,
        ALLOW_CHILD_ROLE_INHERIT = 0,
        UPDATED_AT = SYSTIMESTAMP
    WHERE ID = v_def_id;
  END IF;

  DELETE FROM UM.UM_WORKFLOW_STEP WHERE DEFINITION_ID = v_def_id;
  INSERT INTO UM.UM_WORKFLOW_STEP (ID, DEFINITION_ID, STEP_ORDER, STEP_TYPE, IS_ACTIVE, CONFIG_JSON)
  VALUES (
    UM.S_UM_WORKFLOW_STEP.NEXTVAL, v_def_id, 10, 'NOTIFICATION', 1,
    '{"timing":"ON_ACTION_SUCCESS","channels":["EMAIL"],"templateKey":"BIRTHDAY_USER","audience":{"mode":"CONTEXT","contextRecipient":"createdUser"}}'
  );

  -- Customer birthday pipeline
  BEGIN
    SELECT ID INTO v_def_id
    FROM UM.UM_WORKFLOW_DEFINITION
    WHERE ACTION_CODE = 'EP:' || v_cust_ep AND BUSINESS_ID IS NULL AND STATUS = 'PUBLISHED' AND ROWNUM = 1;
  EXCEPTION
    WHEN NO_DATA_FOUND THEN
      INSERT INTO UM.UM_WORKFLOW_DEFINITION (
        ID, ACTION_CODE, VERSION_NO, STATUS, BUSINESS_ID, DISPLAY_NAME, NOTES,
        PUBLISHED_AT, PUBLISHED_BY, CREATED_BY, CREATED_AT, UPDATED_AT
      ) VALUES (
        UM.S_UM_WORKFLOW_DEFINITION.NEXTVAL, 'EP:' || v_cust_ep, 1, 'PUBLISHED', NULL,
        'Customer birthday email', 'Scheduled daily — WorkflowEngineScheduledTriggerService',
        SYSTIMESTAMP, 'seed', 'seed', SYSTIMESTAMP, SYSTIMESTAMP
      )
      RETURNING ID INTO v_def_id;
  END;

  IF v_has_v2 > 0 THEN
    UPDATE UM.UM_WORKFLOW_DEFINITION
    SET WORKFLOW_TYPE = 'NOTIFICATION_ONLY',
        ROLE_RESTRICTED = 0,
        ALLOW_CHILD_ROLE_INHERIT = 0,
        UPDATED_AT = SYSTIMESTAMP
    WHERE ID = v_def_id;
  END IF;

  DELETE FROM UM.UM_WORKFLOW_STEP WHERE DEFINITION_ID = v_def_id;
  INSERT INTO UM.UM_WORKFLOW_STEP (ID, DEFINITION_ID, STEP_ORDER, STEP_TYPE, IS_ACTIVE, CONFIG_JSON)
  VALUES (
    UM.S_UM_WORKFLOW_STEP.NEXTVAL, v_def_id, 10, 'NOTIFICATION', 1,
    '{"timing":"ON_ACTION_SUCCESS","channels":["EMAIL"],"templateKey":"BIRTHDAY_CUSTOMER","audience":{"mode":"CONTEXT","contextRecipient":"createdCustomer"}}'
  );
END;
