-- Scheduled birthday pipelines (DOMAIN + TRIGGER_KIND=SCHEDULED).
-- Run after: patch-um-workflow-engine-oracle.sql, patch-um-workflow-engine-v2-oracle.sql (optional columns),
--            02-notification-seed-templates.sql (BIRTHDAY_USER / BIRTHDAY_CUSTOMER).
-- UM WorkflowEngineScheduledTriggerService fires BIRTHDAY_*_SUCCESS daily; orchestrator enqueues UM_NOTIF_OUTBOX.

MERGE INTO UM.UM_WORKFLOW_API_ENDPOINT t
USING (
  SELECT 'BIRTHDAY_USER_SUCCESS' AS ENGINE_ACTION_CODE,
         'um' AS SERVICE_KEY, '*' AS HTTP_METHOD, NULL AS PATH_ANT_PATTERN,
         '/um/users' AS SCREEN_ROUTE, 'SCHEDULED' AS ACTION_CODE,
         'User birthday (daily)' AS DISPLAY_NAME,
         'Scheduled — users with DATE_OF_BIRTH matching today' AS DESCRIPTION,
         'SCHEDULED' AS TRIGGER_KIND, 'DOMAIN' AS TRIGGER_SOURCE
  FROM dual
) s ON (t.ENGINE_ACTION_CODE = s.ENGINE_ACTION_CODE)
WHEN NOT MATCHED THEN
  INSERT (ID, SERVICE_KEY, HTTP_METHOD, PATH_ANT_PATTERN, SCREEN_ROUTE, ACTION_CODE, PRIORITY, IS_ACTIVE,
          CREATED_AT, ENGINE_ACTION_CODE, DISPLAY_NAME, DESCRIPTION, TRIGGER_KIND, TRIGGER_SOURCE)
  VALUES (UM.S_UM_WORKFLOW_API_ENDPOINT.NEXTVAL, s.SERVICE_KEY, s.HTTP_METHOD, s.PATH_ANT_PATTERN,
          s.SCREEN_ROUTE, s.ACTION_CODE, 5, 1, SYSTIMESTAMP, s.ENGINE_ACTION_CODE, s.DISPLAY_NAME,
          s.DESCRIPTION, s.TRIGGER_KIND, s.TRIGGER_SOURCE);

