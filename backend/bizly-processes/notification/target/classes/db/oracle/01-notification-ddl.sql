-- Notification workflow tables (schema UM). Run as UM.
-- Email templates + dispatch audit log.

BEGIN
  EXECUTE IMMEDIATE q'[CREATE SEQUENCE UM.NOTIF_EMAIL_TEMPLATE_SEQ START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE]';
EXCEPTION WHEN OTHERS THEN
  IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

BEGIN
  EXECUTE IMMEDIATE q'[CREATE SEQUENCE UM.NOTIF_DISPATCH_LOG_SEQ START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE]';
EXCEPTION WHEN OTHERS THEN
  IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

BEGIN
  EXECUTE IMMEDIATE q'[
CREATE TABLE UM.NOTIF_EMAIL_TEMPLATE (
  ID NUMBER NOT NULL,
  TEMPLATE_KEY VARCHAR2(64 CHAR) NOT NULL,
  SUBJECT_TMPL VARCHAR2(512 CHAR),
  HTML_BODY CLOB,
  TEXT_BODY CLOB,
  ACTIVE_IND CHAR(1 BYTE) DEFAULT 'Y' NOT NULL,
  CONSTRAINT PK_NOTIF_EMAIL_TEMPLATE PRIMARY KEY (ID),
  CONSTRAINT UK_NOTIF_TMPL_KEY UNIQUE (TEMPLATE_KEY),
  CONSTRAINT CK_NOTIF_TMPL_ACTIVE CHECK (ACTIVE_IND IN ('Y','N'))
)]';
EXCEPTION WHEN OTHERS THEN
  IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

BEGIN
  EXECUTE IMMEDIATE q'[
CREATE TABLE UM.NOTIF_DISPATCH_LOG (
  ID NUMBER NOT NULL,
  PROCESS_TYPE VARCHAR2(32 CHAR) NOT NULL,
  TEMPLATE_KEY VARCHAR2(64 CHAR),
  USER_ID NUMBER,
  RECIPIENT_EMAIL VARCHAR2(320 CHAR),
  STATUS VARCHAR2(16 CHAR) NOT NULL,
  ERROR_DETAIL VARCHAR2(4000 CHAR),
  CREATED_AT TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_NOTIF_DISPATCH_LOG PRIMARY KEY (ID)
)]';
EXCEPTION WHEN OTHERS THEN
  IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

BEGIN
  EXECUTE IMMEDIATE 'CREATE INDEX IDX_NOTIF_DISPATCH_USER_DAY ON UM.NOTIF_DISPATCH_LOG (USER_ID, PROCESS_TYPE, CREATED_AT)';
EXCEPTION WHEN OTHERS THEN
  IF SQLCODE != -955 THEN RAISE; END IF;
END;
/
