BEGIN
  EXECUTE IMMEDIATE q'[CREATE SEQUENCE UM.NOTIF_BROADCAST_MESSAGE_SEQ START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE]';
EXCEPTION WHEN OTHERS THEN
  IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

BEGIN
  EXECUTE IMMEDIATE q'[CREATE SEQUENCE UM.NOTIF_BROADCAST_RCPT_SEQ START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE]';
EXCEPTION WHEN OTHERS THEN
  IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

BEGIN
  EXECUTE IMMEDIATE q'[
CREATE TABLE UM.NOTIF_BROADCAST_MESSAGE (
  ID NUMBER NOT NULL,
  SUBJECT VARCHAR2(512 CHAR) NOT NULL,
  BODY CLOB NOT NULL,
  TARGET_TYPE VARCHAR2(32 CHAR) NOT NULL,
  TARGET_ROLE_ID NUMBER,
  CUSTOM_SEGMENT_JSON CLOB,
  STATUS VARCHAR2(20 CHAR) DEFAULT ''PENDING'' NOT NULL,
  DELIVERY_REQUESTED NUMBER(1) DEFAULT 0 NOT NULL,
  CREATED_AT TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
  SENT_AT TIMESTAMP(6),
  CREATED_BY VARCHAR2(200 CHAR),
  CONSTRAINT PK_NOTIF_BROADCAST_MSG PRIMARY KEY (ID),
  CONSTRAINT CK_NOTIF_BCAST_STATUS CHECK (STATUS IN (''PENDING'',''PROCESSING'',''SENT'',''FAILED''))
)]';
EXCEPTION WHEN OTHERS THEN
  IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

BEGIN
  EXECUTE IMMEDIATE q'[
CREATE TABLE UM.NOTIF_BROADCAST_RCPT (
  ID NUMBER NOT NULL,
  BROADCAST_MESSAGE_ID NUMBER NOT NULL,
  RECIPIENT_EMAIL VARCHAR2(320 CHAR) NOT NULL,
  STATUS VARCHAR2(16 CHAR) NOT NULL,
  ERROR_DETAIL VARCHAR2(4000 CHAR),
  SENT_AT TIMESTAMP(6),
  CONSTRAINT PK_NOTIF_BROADCAST_RCPT PRIMARY KEY (ID),
  CONSTRAINT FK_NOTIF_BCAST_RCPT_MSG FOREIGN KEY (BROADCAST_MESSAGE_ID) REFERENCES UM.NOTIF_BROADCAST_MESSAGE (ID),
  CONSTRAINT UK_NOTIF_BCAST_RCPT UNIQUE (BROADCAST_MESSAGE_ID, RECIPIENT_EMAIL)
)]';
EXCEPTION WHEN OTHERS THEN
  IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

BEGIN
  EXECUTE IMMEDIATE 'CREATE INDEX IDX_NOTIF_BCAST_STATUS ON UM.NOTIF_BROADCAST_MESSAGE (STATUS, DELIVERY_REQUESTED, CREATED_AT)';
